"""Period report -> Excel workbook: one sheet per topic, one row per day/equipment, all alarms and history."""
import io
import json
from datetime import datetime

from openpyxl import Workbook
from openpyxl.styles import Alignment, Font, PatternFill
from openpyxl.utils import get_column_letter

from infra_reports.config import REPORT_TZ

from .period import CATEGORIES

HEAD_FILL = PatternFill("solid", fgColor="263238")
HEAD_FONT = Font(bold=True, color="FFFFFF")
TITLE_FONT = Font(bold=True, size=14)


def _dt(ts):
    return datetime.fromtimestamp(ts / 1000, REPORT_TZ).replace(tzinfo=None) if ts else None


def _st(s, k):
    return (s or {}).get(k) if s else None


def _sheet(wb, title, headers, rows, widths=None, first=False):
    ws = wb.active if first else wb.create_sheet()
    ws.title = title[:31]
    ws.append(headers)
    for c in range(1, len(headers) + 1):
        cell = ws.cell(row=1, column=c)
        cell.fill, cell.font = HEAD_FILL, HEAD_FONT
        cell.alignment = Alignment(vertical="center", wrap_text=True)
    for r in rows:
        ws.append(r)
    ws.freeze_panes = "A2"
    if rows:
        ws.auto_filter.ref = f"A1:{get_column_letter(len(headers))}{len(rows) + 1}"
    for i, h in enumerate(headers, 1):
        w = (widths or {}).get(h) or max(10, min(45, len(h) + 2, *[len(str(r[i - 1])) + 2 for r in rows[:200] if r[i - 1] is not None] or [10]))
        ws.column_dimensions[get_column_letter(i)].width = w
    for row in ws.iter_rows(min_row=2):
        for cell in row:
            if isinstance(cell.value, datetime):
                cell.number_format = "dd-mmm-yyyy hh:mm"
            elif isinstance(cell.value, float):
                cell.number_format = "#,##0.00"
    return ws


def render_xlsx(p):
    wb = Workbook()
    devs = p["devices"]
    # ---- Summary
    ws = wb.active
    ws.title = "Summary"
    ws.append([f'{p["label"]} Equipment Performance & Maintenance Report'])
    ws["A1"].font = TITLE_FONT
    ws.append(["Period", f'{p["start"]:%d %b %Y} - {p["end"]:%d %b %Y} ({len(p["days"])} days, IST)'])
    ws.append(["Generated", p["generated_at"].strftime("%d %b %Y %H:%M IST")])
    if p.get("generated_by"):
        ws.append(["Generated by", p["generated_by"]])
    if p["partial_days"]:
        ws.append(["Note", f'{", ".join(p["partial_days"])} in progress: values up to generation time'])
    ws.append([])
    head = ["Equipment", "Category", "Data availability %", "Alarms", "Critical alarms", "Maintenance records",
            "Health now", "Status now", "Main finding", "Recommended action", "Service due (run-h)", "Last maintenance"]
    ws.append(head)
    hr = ws.max_row
    for c in range(1, len(head) + 1):
        ws.cell(row=hr, column=c).fill, ws.cell(row=hr, column=c).font = HEAD_FILL, HEAD_FONT
    for d in devs:
        o = d["outlook"]
        lm = o["last_maintenance"]
        ws.append([d["name"], CATEGORIES[d["category"]], d["availability_pct"], len(d["alarms"]),
                   sum(1 for a in d["alarms"] if a.get("severity") == "CRITICAL"),
                   sum(1 for m in p["maintenance"] if m["device"] == d["name"]), o["health"], o["severity"],
                   o["top_issue"], o["recommendation"], o["service_due_h"] if d["category"] == "dg" else None,
                   _dt(lm["ts"]) if lm else None])
    for i, w in enumerate([28, 16, 12, 9, 9, 12, 10, 11, 45, 55, 12, 18], 1):
        ws.column_dimensions[get_column_letter(i)].width = w
    for row in ws.iter_rows(min_row=hr + 1):
        for cell in row:
            if isinstance(cell.value, datetime):
                cell.number_format = "dd-mmm-yyyy hh:mm"
    ws.column_dimensions["A"].width = 28

    # ---- DG daily
    dg = [d for d in devs if d["category"] == "dg"]
    if dg:
        rows = []
        for d in dg:
            for x in d["days"]:
                fu = x.get("fuel") or {}
                st = x.get("stats", {})
                rows.append([x["date"], d["name"], x.get("run_hours"), x.get("runs"), x.get("energy_kwh"),
                             fu.get("start"), fu.get("end"), fu.get("min"), fu.get("consumed_pct"),
                             "lower bound" if fu.get("lower_bound") else None, fu.get("refuelled_pct"),
                             fu.get("refuel_count"), _st(st.get("battery_voltage"), "min"),
                             _st(st.get("battery_voltage"), "avg"), _st(st.get("coolant_temp"), "max"),
                             _st(st.get("oil_pressure"), "min"), _st(st.get("power_kw"), "max"),
                             x.get("run_hours_total"), x.get("availability_pct"), len(x["alarms"]),
                             (x.get("pm") or {}).get("health_avg")])
        _sheet(wb, "DG Daily", ["Date", "DG", "Run hours", "Runs", "Energy kWh", "Fuel start %", "Fuel end %",
                                "Fuel min %", "Fuel used %", "Fuel note", "Refuelled %", "Refuels",
                                "Battery min V", "Battery avg V", "Coolant max C", "Oil pressure min kPa",
                                "Power max kW", "Run-hour meter", "Data %", "Alarms", "PM health avg"], rows)
    # ---- LT daily
    lt = [d for d in devs if d["category"] == "lt"]
    if lt:
        rows = []
        for d in lt:
            for x in d["days"]:
                for key, f in x.get("feeders", {}).items():
                    v, c, pw, fq = f.get("voltage"), f.get("current"), f.get("power"), f.get("frequency")
                    rows.append([x["date"], d["name"], f["label"], f.get("energy_kwh"), _st(v, "avg"), _st(v, "min"),
                                 _st(v, "max"), _st(c, "avg"), _st(c, "max"), _st(pw, "avg"), _st(pw, "max"),
                                 _st(fq, "min"), _st(fq, "max"), f.get("coverage_pct")])
        _sheet(wb, "LT Daily", ["Date", "Panel", "Feeder", "Energy kWh", "Voltage avg V", "Voltage min V",
                                "Voltage max V", "Current avg A", "Current max A", "Power avg kW", "Power max kW",
                                "Frequency min Hz", "Frequency max Hz", "Data %"], rows)
    # ---- RO daily
    ro = [d for d in devs if d["category"] == "ro"]
    if ro:
        rows = []
        for d in ro:
            for x in d["days"]:
                st = x.get("stats", {})
                rows.append([x["date"], d["name"]] + [_st(st.get(k), m) for k, m in (
                    ("tds_ppm", "avg"), ("tds_ppm", "min"), ("tds_ppm", "max"), ("ec_us_cm", "avg"),
                    ("temperature_c", "avg"), ("temperature_c", "max"), ("ph", "avg"), ("pressure", "avg"))]
                            + [x.get("availability_pct"), len(x["alarms"])])
        _sheet(wb, "RO Daily", ["Date", "Plant", "TDS avg ppm", "TDS min ppm", "TDS max ppm", "EC avg uS/cm",
                                "Temp avg C", "Temp max C", "pH avg", "Pressure avg bar", "Data %", "Alarms"], rows)
    # ---- Fire daily
    fire = [d for d in devs if d["category"] == "fire"]
    if fire:
        rows = []
        for d in fire:
            for x in d["days"]:
                for n, c in sorted(x.get("channels", {}).items(), key=lambda kv: int(kv[0])):
                    rows.append([x["date"], d["name"], f"Cylinder {n}", c["ok_pct"], c["changes"],
                                 "NORMAL" if c["last"] else "LOW", c["samples"]])
        _sheet(wb, "Fire Daily", ["Date", "System", "Channel", "Time at normal pressure %", "Signal changes",
                                  "State at day end", "Samples"], rows)
    # ---- Alarms
    rows = []
    for a in p["alarms"]:
        st, cl = a.get("start_ts"), a.get("clear_ts")
        rows.append([_dt(st), _dt(cl), round((cl - st) / 60000, 1) if st and cl else None, a["device"],
                     a.get("type"), a.get("severity"), a.get("status")])
    _sheet(wb, "Alarms", ["Raised", "Cleared", "Duration min", "Equipment", "Alarm", "Severity", "Status"], rows,
           {"Raised": 18, "Cleared": 18, "Alarm": 36})
    # ---- Maintenance & events
    rows = []
    for m in p["maintenance"]:
        rows.append([_dt(m["ts"]), m["device"], "Maintenance", m.get("type"), m.get("description"),
                     m.get("technician"), m.get("run_hours"), m.get("parts"), m.get("cost"), m.get("next_due")])
    for e in p["events"]:
        rows.append([_dt(e["ts"]), e["device"], "Automatic", e["kind"], e["text"], None, None, None, None, None])
    rows.sort(key=lambda r: r[0] or datetime.min)
    _sheet(wb, "Maintenance & Events", ["When", "Equipment", "Source", "Type", "Description", "Technician",
                                        "Run hours", "Parts", "Cost", "Next due"], rows,
           {"When": 18, "Description": 60})
    # ---- PM daily
    rows = []
    for d in devs:
        for x in d["days"]:
            pm = x.get("pm")
            if pm:
                rows.append([x["date"], d["name"], pm["health_avg"], pm["health_min"], pm["worst"],
                             pm["warning_min"], pm["critical_min"], "; ".join(pm["top_issues"])])
    if rows:
        _sheet(wb, "Predictive Health", ["Date", "Equipment", "Health avg", "Health min", "Worst status",
                                         "Minutes WARNING", "Minutes CRITICAL", "Main issues"], rows,
               {"Main issues": 70})
    buf = io.BytesIO()
    wb.save(buf)
    return buf.getvalue()
